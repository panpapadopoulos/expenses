export interface Expense {
  id: string;
  date: string; // ISO date, YYYY-MM-DD
  merchant: string;
  amount: number;
  categoryId: string;
  accountId: string;
  notes?: string;
  recurringId?: string; // set if this expense was generated by a RecurringExpense template
}

export interface RecurringExpense {
  id: string;
  merchant: string;
  amount: number;
  categoryId: string;
  accountId: string;
  notes?: string;
  frequency: 'monthly';
  startDate: string; // ISO date of the first occurrence
  occurrences?: number; // undefined = ongoing indefinitely; number = ends after N payments
  active: boolean; // false once cancelled or all occurrences have been generated
}

export interface Category {
  id: string;
  name: string;
  color: string;
}

export interface Account {
  id: string;
  name: string;
  type: string;
}

export interface AppData {
  expenses: Expense[];
  categories: Category[];
  accounts: Account[];
  recurringExpenses: RecurringExpense[];
}

export type SortField = 'date' | 'amount' | 'merchant' | 'category';
export type SortOrder = 'asc' | 'desc';
export type Tab = 'dashboard' | 'expenses' | 'add' | 'categories' | 'accounts' | 'settings';
